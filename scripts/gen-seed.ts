import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { readSnapshot, seedStatements } from "../db/seed-data";

async function main(): Promise<void> {
  const root = "netlify/database/migrations";
  await mkdir(root, { recursive: true });
  const existing = (await readdir(root)).find(name => name.endsWith("_seed_roboarena"));
  const folder = existing ?? `${new Date().toISOString().replace(/\D/g, "").slice(0, 14)}_seed_roboarena`;
  const sql = "-- RoboArena DataDump (MIT). Generated by scripts/gen-seed.ts.\n" +
    seedStatements(await readSnapshot()).join("\n--> statement-breakpoint\n") + "\n";
  const path = join(root, folder, "migration.sql");
  if (existing) {
    if (await readFile(path, "utf8") !== sql) throw new Error("Snapshot changed: create a new migration; never rewrite an applied seed migration");
    console.log(`Seed migration unchanged: ${path}`);
    return;
  }
  await mkdir(join(root, folder), { recursive: true });
  await writeFile(path, sql, "utf8");
  console.log(`Generated ${path}`);
}
main().catch(() => { console.error("Seed generation failed; validate the snapshot and existing migration."); process.exitCode = 1; });
