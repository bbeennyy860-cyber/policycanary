/**
 * Reproducible calibration of the gate's two headline claims on every RoboArena policy pair with at
 * least MIN_PAIRS paired sessions. Run `npm run calibrate`; it rewrites docs/CALIBRATION.md
 * deterministically (fixed seeds, no timestamps), so a re-run should produce no diff.
 *
 * (a) Null calibration. Each real paired difference has its sign flipped at random, which is the same
 *     as swapping which arm is "baseline" within that session. The true mean is then exactly zero, so
 *     any declared winner is false. Naive repeated t-tests are compared against the confidence sequence.
 * (b) Time to decision. The gate's first decision on the real, time-ordered data is compared against
 *     the pairs a fixed-sample test needs when its minimum detectable effect (MDE) is chosen in advance.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { DEFAULT_GATE } from "../lib/contract";
import { getPairsFromData, policyNames } from "../lib/data";
import { runGate } from "../lib/stats/decide";
import { moments, studentTCdf } from "../lib/stats/math";
import { simulatePeeking } from "../lib/stats/peeking";
import { fixedHorizonPairs } from "../lib/stats/savings";
import { wilson } from "../lib/stats/wilson";

const MIN_PAIRS = 30;
const REPLICATIONS = 400;
const PEEK_EVERY = 10;
const SEED = 20261021;
const MDES = [0.05, 0.075, 0.1, 0.125, 0.15];
const OUT = "docs/CALIBRATION.md";

interface PairRow {
  base: string; cand: string; n: number; sigma: number; meanAbs: number;
  naiveFalse: number; csFalse: number; verdict: string; decidedAt: number; fixed: number[];
  fixedSignificant: (boolean | null)[]; // null: the planned size exceeds the available pairs
}

/** Two-sided one-sample t-test on the first n diffs, as the fixed-sample design would run it once. */
function fixedTestRejects(ds: number[], n: number, alpha: number): boolean | null {
  if (!Number.isFinite(n) || n > ds.length || n < 2) return null;
  const m = moments(ds.slice(0, n));
  if (m.variance <= 0) return m.mean !== 0;
  const t = m.mean / Math.sqrt(m.variance / n);
  return 2 * (1 - studentTCdf(Math.abs(t), n - 1)) < alpha;
}

const median = (xs: number[]): number => {
  if (!xs.length) return NaN;
  const s = [...xs].sort((a, b) => a - b), mid = s.length >> 1;
  return s.length % 2 ? s[mid] : (s[mid - 1] + s[mid]) / 2;
};
const pct = (v: number, digits = 1) => `${(v * 100).toFixed(digits)}%`;
const fmtN = (v: number) => (Number.isFinite(v) ? String(v) : "∞");

function collect(): PairRow[] {
  const names = [...policyNames()].sort();
  const rows: PairRow[] = [];
  for (let i = 0; i < names.length; i++) {
    for (let j = i + 1; j < names.length; j++) {
      const ds = getPairsFromData(names[i], names[j]).map(p => p.d);
      if (ds.length < MIN_PAIRS) continue;
      // Distinct seed per pair so replications are independent across pairs; production grid (999 points).
      const sim = simulatePeeking(ds, { replications: REPLICATIONS, seed: SEED + rows.length, alpha: DEFAULT_GATE.alpha,
        peekEvery: PEEK_EVERY, gridDenominator: 1000 });
      const gate = runGate(ds, DEFAULT_GATE);
      const m = moments(ds), sigma = Math.sqrt(m.variance);
      const fixed = MDES.map(mde => fixedHorizonPairs(sigma, mde, DEFAULT_GATE.alpha));
      rows.push({ base: names[i], cand: names[j], n: ds.length, sigma, meanAbs: Math.abs(m.mean),
        naiveFalse: sim.naiveFalseDecisions, csFalse: sim.csFalseDecisions,
        verdict: gate.decision.verdict, decidedAt: gate.decidedAt, fixed,
        fixedSignificant: fixed.map(n => fixedTestRejects(ds, n, DEFAULT_GATE.alpha)) });
    }
  }
  return rows;
}

function report(rows: PairRow[]): string {
  const reps = rows.length * REPLICATIONS;
  const naive = rows.reduce((s, r) => s + r.naiveFalse, 0), cs = rows.reduce((s, r) => s + r.csFalse, 0);
  const [nLo, nHi] = wilson(naive, reps), [cLo, cHi] = wilson(cs, reps);
  const worst = rows.reduce((a, b) => (b.csFalse > a.csFalse ? b : a));
  const over = rows.filter(r => r.csFalse / REPLICATIONS > DEFAULT_GATE.alpha).length;
  const decided = rows.filter(r => r.verdict === "PROMOTE" || r.verdict === "ROLLBACK");
  const obs = rows.reduce((s, r) => s + r.n, 0);

  const L: string[] = [];
  L.push("# Calibration", "");
  L.push("Generated by `npm run calibrate` (`scripts/calibrate.ts`). Fixed seeds, so a re-run reproduces this file exactly.", "");
  L.push(`Scope: every pair of the 21 RoboArena policies with at least ${MIN_PAIRS} paired sessions: **${rows.length} pairs, ${obs.toLocaleString("en-GB")} paired observations**. ` +
    `Gate settings: α = ${DEFAULT_GATE.alpha}, ${DEFAULT_GATE.mode}, rollback margin ${DEFAULT_GATE.margin}.`, "");

  L.push("## (a) False decisions when there is no real difference", "");
  L.push(`Each real paired difference has its sign flipped at random (the same as swapping which arm is baseline in that session), so the true mean is exactly 0 and any declared winner is wrong. ` +
    `${REPLICATIONS} replications per pair. "Naive" runs a two-sided t-test every ${PEEK_EVERY} pairs and stops at the first p < ${DEFAULT_GATE.alpha}. ` +
    `"Confidence sequence" counts any point where the interval excludes 0, which includes every false PROMOTE or ROLLBACK the gate could make.`, "");
  L.push("| | False-decision rate | 95% interval | Replications |", "|---|---|---|---|");
  L.push(`| Naive peeking | **${pct(naive / reps)}** | ${pct(nLo)} – ${pct(nHi)} | ${reps.toLocaleString("en-GB")} |`);
  L.push(`| Confidence sequence | **${pct(cs / reps, 2)}** | ${pct(cLo, 2)} – ${pct(cHi, 2)} | ${reps.toLocaleString("en-GB")} |`);
  L.push("", `Target: at most ${pct(DEFAULT_GATE.alpha, 0)}. Highest single-pair confidence-sequence rate: ${pct(worst.csFalse / REPLICATIONS)} ` +
    `(${worst.base} → ${worst.cand}, n = ${worst.n}). Pairs above ${pct(DEFAULT_GATE.alpha, 0)}: ${over} of ${rows.length} ` +
    `(with ${REPLICATIONS} replications a single pair's rate has a standard error of about 1 percentage point).`, "");
  L.push(`The confidence sequence is conservative here: it uses about ${pct(cs / reps, 0)} of a ${pct(DEFAULT_GATE.alpha, 0)} error budget. That slack is the price of being valid at every look, and it is why the gate holds on small effects that a fixed test sized for them would detect (section b).`, "");
  L.push("**What this does not test:** the guarantee assumes the mean difference is constant over time. Sign flipping keeps the real magnitudes and their order but forces the mean to 0, so drift in the mean (evaluator, site or date effects changing over time) is outside this check.", "");

  L.push("## (b) Time to decision vs a fixed-sample test", "");
  L.push(`The gate replays each pair's real sessions in time order and stops at its first decision. A fixed-sample test must commit to a size before any data arrive: ` +
    `n = ((z₁₋α/₂ + z₀.₈) σ / MDE)², two-sided α = ${DEFAULT_GATE.alpha}, 80% power. σ is each pair's observed standard deviation, which is generous to the fixed test ` +
    `(a planner would only have an estimate). The gate reached a decision on **${decided.length} of ${rows.length}** pairs; the rest ran out of data (HOLD).`, "");
  L.push("| MDE chosen in advance | Median fixed-sample n | Fixed test fits in the data | Fixed test finds a difference | Gate decided before the fixed n | Median gate n (decided) |",
    "|---|---|---|---|---|---|");
  const gateMedian = median(decided.map(r => r.decidedAt));
  MDES.forEach((mde, k) => {
    const fits = rows.filter(r => r.fixed[k] <= r.n).length;
    const significant = rows.filter(r => r.fixedSignificant[k] === true).length;
    const faster = decided.filter(r => r.decidedAt < r.fixed[k]).length;
    L.push(`| ${mde} | ${median(rows.map(r => r.fixed[k]))} | ${fits} of ${rows.length} | ${significant} of ${fits} | ${faster} of ${rows.length} | ${gateMedian} |`);
  });
  L.push("", `"Fixed test finds a difference" runs the planned two-sided t-test once, on the first n sessions in time order. ` +
    `"Gate decided before the fixed n" counts all ${rows.length} pairs; a pair the gate never decided counts as not faster.`, "");
  L.push("Reading it: a fixed test sized for a small effect is slow whatever the truth turns out to be; one sized for a large effect is fast but misses smaller real differences. The gate needs no MDE, adapts to the effect that is actually there, and can stop early in either direction. The price is that it needs more pairs than a fixed test sized for exactly the right effect.", "");

  L.push("### Per pair", "", "Pairs are listed alphabetically with the first name as baseline, so PROMOTE means the second policy is better.", "");
  L.push(`| Baseline → candidate | n | |mean d| | σ | Gate | Decided at | Fixed n @ ${MDES[0]} | @ ${MDES[2]} | @ ${MDES[4]} | Null: naive | Null: CS |`,
    "|---|---|---|---|---|---|---|---|---|---|---|");
  for (const r of [...rows].sort((a, b) => b.n - a.n)) {
    L.push(`| ${r.base} → ${r.cand} | ${r.n} | ${r.meanAbs.toFixed(3)} | ${r.sigma.toFixed(3)} | ${r.verdict} | ${r.decidedAt} | ` +
      `${fmtN(r.fixed[0])} | ${fmtN(r.fixed[2])} | ${fmtN(r.fixed[4])} | ${pct(r.naiveFalse / REPLICATIONS)} | ${pct(r.csFalse / REPLICATIONS)} |`);
  }
  return L.join("\n") + "\n";
}

async function main(): Promise<void> {
  const started = Date.now();
  const md = report(collect());
  await mkdir("docs", { recursive: true });
  await writeFile(OUT, md, "utf8");
  console.log(md);
  console.log(`wrote ${OUT} in ${((Date.now() - started) / 1000).toFixed(1)} s`);
}

main().catch(err => { console.error(err); process.exit(1); });
